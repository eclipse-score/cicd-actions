'use strict';

const { execFileSync } = require('child_process');

const KVM_DEVICE = '/dev/kvm';

function hasCommand(cmd) {
  try {
    execFileSync('which', [cmd], { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
}

module.exports = { KVM_DEVICE, hasCommand };
